import { PenTool } from '../types/note';

/**
 * Utilities for Samsung S Pen, Apple Pencil and Wacom Stylus pointer event handling
 */

/**
 * Checks if the pointer event has the barrel button (side button) or eraser button pressed.
 * - buttons & 4: W3C auxiliary / middle button (Chromium on Android / Samsung Galaxy Tab S Pen mapping!)
 * - buttons & 2: W3C secondary / barrel button (Windows / Wacom / Surface Pen)
 * - buttons & 32: W3C eraser tip / barrel eraser (or Android MotionEvent.BUTTON_STYLUS_PRIMARY bitmask)
 * - button === 1: Android Chrome S Pen side button click
 * - button === 2: Secondary button click
 * - button === 5: Eraser button click
 */
export function isSpenBarrelOrEraser(buttons: number, button?: number): boolean {
  return (
    (buttons & 4) !== 0 ||
    (buttons & 2) !== 0 ||
    (buttons & 32) !== 0 ||
    button === 1 ||
    button === 2 ||
    button === 5
  );
}

/**
 * Determines whether the physical S Pen side button is currently PRESSED / HELD DOWN.
 * 
 * 1. While Hovering in the air (pressure <= 0.05):
 *    Normal hovering has buttons === 0 and button <= 0.
 *    Any non-zero buttons or button > 0 indicates the side button is pressed in the air.
 * 
 * 2. While Touching the screen (pressure > 0.05):
 *    Normal tip contact is buttons === 1 (primary button).
 *    Tip contact MUST NOT be mistaken for a barrel button press.
 *    The side button is active only if auxiliary/secondary bits are set:
 *    (buttons & 4) !== 0, (buttons & 2) !== 0, (buttons & 32) !== 0,
 *    or button === 1, button === 2, button === 5.
 */
export function isSpenButtonPressed(buttons: number, button?: number, pressure: number = 0): boolean {
  if (pressure <= 0.05) {
    if (buttons > 0) return true;
    if (button !== undefined && button > 0 && button !== -1) return true;
    return false;
  }

  // When touching the screen, button tip contact alone (buttons === 1, button === 0) is regular inking
  return (
    (buttons & 4) !== 0 ||
    (buttons & 2) !== 0 ||
    (buttons & 32) !== 0 ||
    (button !== undefined && (button === 1 || button === 2 || button === 5))
  );
}

/**
 * Checks if a key event is generated by an Android 14+ / One UI Stylus hardware button.
 * Android KEYCODE_STYLUS_BUTTON_PRIMARY = 308
 * Android KEYCODE_STYLUS_BUTTON_SECONDARY = 309
 */
export function isSpenHardwareKeyEvent(e: KeyboardEvent): boolean {
  return (
    e.keyCode === 308 ||
    e.keyCode === 309 ||
    e.which === 308 ||
    e.which === 309 ||
    e.code === 'StylusButtonPrimary' ||
    e.code === 'StylusButtonSecondary' ||
    e.key === 'StylusButton' ||
    e.key === 'StylusButtonPrimary'
  );
}

/**
 * Evaluates whether an S Pen button interaction was a "Keep Pressing" (Hold to Erase)
 * or a "Press Once" (Single Click to open Pen & Color Menu).
 */
export function evaluateSpenButtonAction(
  pressDurationMs: number,
  hasErasedOrMoved: boolean,
  isHolding: boolean,
  holdThresholdMs: number = 250
): 'hold-eraser' | 'single-click-menu' {
  if (isHolding || hasErasedOrMoved || pressDurationMs >= holdThresholdMs) {
    return 'hold-eraser';
  }
  return 'single-click-menu';
}

/**
 * Toggles the active pen tool when the S Pen button is pressed.
 * Seamlessly flips between the user's active pen (e.g. fountain or ballpoint) and eraser.
 */
export function toggleSpenHoverTool(
  currentTool: PenTool,
  priorTool?: PenTool
): { nextTool: PenTool; savedPriorTool: PenTool; label: string } {
  if (currentTool === 'eraser') {
    const next = priorTool || 'fountain';
    return {
      nextTool: next,
      savedPriorTool: next,
      label: next === 'fountain' ? 'Fountain Pen' : next === 'highlighter' ? 'Highlighter' : 'Ballpoint Pen'
    };
  }

  return {
    nextTool: 'eraser',
    savedPriorTool: currentTool,
    label: 'Eraser'
  };
}
